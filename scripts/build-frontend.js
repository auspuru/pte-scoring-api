'use strict';
const fs = require('node:fs');
const path = require('node:path');

const root = path.join(__dirname, '..');
const htmlPath = path.join(root, 'public', 'index.html');
const cssPath = path.join(root, 'public', 'utility.css');

const css = `/* Generated by scripts/build-frontend.js. Do not edit by hand. */
.flex{display:flex}
.flex-1{flex:1 1 0%}
.flex-col{flex-direction:column}
.gap-1{gap:.25rem}
.gap-2{gap:.5rem}
.gap-4{gap:1rem}
.gap-6{gap:1.5rem}
.hidden{display:none}
.items-center{align-items:center}
.max-w-\\[1200px\\]{max-width:1200px}
.mx-auto{margin-left:auto;margin-right:auto}
.overflow-y-auto{overflow-y:auto}
.p-container-padding{padding:24px}
.text-\\[20px\\]{font-size:20px}
.text-\\[22px\\]{font-size:22px}
.transition-all{transition-property:all;transition-duration:150ms;transition-timing-function:cubic-bezier(.4,0,.2,1)}
.duration-1000{transition-duration:1000ms}
.w-full{width:100%}
`;

function assertProductionHtml(html) {
  if (/cdn\.tailwindcss\.com/i.test(html)) {
    throw new Error('Production HTML must not load the Tailwind Play CDN.');
  }
  if (/tailwind\.config\s*=/.test(html)) {
    throw new Error('Production HTML must not contain runtime Tailwind configuration.');
  }
  if (!/href=["']utility\.css\?v=1["']/.test(html)) {
    throw new Error('Production HTML must load utility.css?v=1.');
  }
  if (/\\n(?=<(?:script|link|style)\b)/.test(html)) {
    throw new Error('Production HTML contains a literal \\n before a head asset tag.');
  }
}

function build() {
  const html = fs.readFileSync(htmlPath, 'utf8');
  assertProductionHtml(html);
  fs.writeFileSync(cssPath, css);
  console.log('Built public/utility.css (' + Buffer.byteLength(css) + ' bytes).');
}

if (require.main === module) build();
module.exports = { build, assertProductionHtml, css };
