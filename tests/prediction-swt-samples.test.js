'use strict';
const test = require('node:test');
const assert = require('node:assert/strict');
const predictions = require('../content/writing-predictions-sep-2026');
const policy = require('../writing-lab-scoring');
const { validatePredictionSwtSamples, longestCopiedRun } = require('../scripts/validate-prediction-swt-samples');

test('all 18 September SWT samples are one-sentence synthesised benchmark answers', () => {
  const result = validatePredictionSwtSamples();
  assert.equal(result.count, 18);
  assert.equal(result.fullLocalBenchmark, 18);
  assert(result.maxCopiedRun < 12);

  for (const q of predictions.swt) {
    assert.equal(policy.formFor('swt', q.sample).score, 1, q.id);
    assert.equal(policy.sentenceCount(q.sample), 1, q.id);
    assert.equal(policy.localGrade(q, q.sample).scores.content, 4, q.id);
    assert(longestCopiedRun(q.text, q.sample) < 12, q.id);
    assert.equal(q.sampleReview.teacherEditable, true, q.id);
    assert.equal(q.sampleReview.humanReview, 'pending', q.id);
  }
});

test('September SWT samples are not generated by concatenating the first source notes', () => {
  for (const q of predictions.swt) {
    const firstKeyPoint = q.keyPoints[0].replace(/[.?!]+$/, '');
    assert.notEqual(q.sample.startsWith(firstKeyPoint), true, q.id + ' still begins with a copied source sentence');
  }
});
